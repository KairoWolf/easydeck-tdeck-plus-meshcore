#!/usr/bin/env python3
"""EasyDeck logo: docs/logo/easydeck.svg -> PNGs for the README / GitHub, and C images for the
T-Deck (LVGL RGB565A8 for the UI, plain RGB565 on the boot-splash background for LovyanGFX).
  python3 tools/gen_logo.py   (needs rsvg-convert and Pillow)"""
import os, subprocess, io
from PIL import Image, ImageDraw, ImageFont

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = os.path.join(root, "docs", "logo", "easydeck.svg")
def render(size):
    png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), svg], check=True, capture_output=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")

out = os.path.join(root, "docs", "logo")
for s in (512, 128):
    render(s).save(os.path.join(out, f"easydeck-{s}.png"))

# GitHub social preview 1280x640: mark + wordmark + tagline
W, H = 1280, 640
img = Image.new("RGBA", (W, H), (10, 10, 10, 255))
mark = render(300)
img.alpha_composite(mark, (110, (H - 300) // 2))
fonts = os.path.join(root, "tools", "fonts")
big = ImageFont.truetype(os.path.join(fonts, "BarlowSemiCondensed-Bold.ttf"), 150)
small = ImageFont.truetype(os.path.join(fonts, "BarlowSemiCondensed-Medium.ttf"), 40)
d = ImageDraw.Draw(img)
d.text((460, 175), "Easy", font=big, fill=(242, 242, 242, 255))
w = d.textlength("Easy", font=big)
d.text((460 + w, 175), "Deck", font=big, fill=(255, 176, 0, 255))
d.text((464, 360), "MeshCore firmware for the LilyGO T-Deck Plus", font=small, fill=(156, 156, 156, 255))
d.text((464, 418), "Messaging · family tracking · SOS · offline maps", font=small, fill=(156, 156, 156, 255))
img.convert("RGB").save(os.path.join(out, "social-preview.png"))

def rgb565(r, g, b): return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

lines = ["// Generated by tools/gen_logo.py from docs/logo/easydeck.svg - do not edit.", '#include "lvgl.h"', "#include <stdint.h>", ""]
for s in (96, 64):
    im = render(s); px = im.load()
    rgb, a = bytearray(), bytearray()
    for y in range(s):
        for x in range(s):
            r, g, b, al = px[x, y]
            v = rgb565(r, g, b); rgb += bytes((v & 0xFF, v >> 8)); a.append(al)
    data = bytes(rgb + a)
    lines.append(f"static const uint8_t logo{s}_d[] = {{" + ",".join(map(str, data)) + "};")
    lines.append(f"const lv_image_dsc_t easydeck_logo_{s} = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0, .w = {s}, .h = {s}, .stride = {s * 2} }}, .data_size = {len(data)}, .data = logo{s}_d }};")
# boot splash: 96x96 RGB565 (native order, LovyanGFX pushImage) flattened on the splash background (0x0841 = #080808)
bg = (8, 8, 8)
im = render(96); px = im.load(); vals = []
for y in range(96):
    for x in range(96):
        r, g, b, al = px[x, y]
        r = (r * al + bg[0] * (255 - al)) // 255; g = (g * al + bg[1] * (255 - al)) // 255; b = (b * al + bg[2] * (255 - al)) // 255
        vals.append(rgb565(r, g, b))
lines.append("const uint16_t easydeck_splash_logo_96[96 * 96] = {" + ",".join(str(v) for v in vals) + "};")
open(os.path.join(root, "firmware", "src", "ui", "Logo.c"), "w").write("\n".join(lines) + "\n")
print("logo: docs/logo/*.png, firmware/src/ui/Logo.c")
