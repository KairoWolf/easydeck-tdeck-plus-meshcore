#!/usr/bin/env python3
"""Embed packs/*.txt (listed in packs/index.txt) into the firmware as built-in settings packs.
Run after editing a pack: python3 tools/gen_packs.py  ->  firmware/src/ui/BuiltinPacks.inc"""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['// Generated by tools/gen_packs.py from packs/*.txt - do not edit.']
ids = []
for line in open(os.path.join(root, 'packs', 'index.txt'), encoding='utf-8'):
    line = line.strip()
    if not line or line.startswith('#'): continue
    ids.append(line.split('|')[0])
out.append('static const char* const kBuiltinPacks[] = {')
for pid in ids:
    text = open(os.path.join(root, 'packs', pid + '.txt'), encoding='utf-8').read()
    lines = [l for l in text.splitlines() if l.strip() and not l.lstrip().startswith('#')]
    out.append('  // ' + pid)
    for l in lines:
        out.append('  "' + l.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
    out.append('  ,')
out.append('};')
open(os.path.join(root, 'firmware', 'src', 'ui', 'BuiltinPacks.inc'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('built-in packs:', ', '.join(ids))
