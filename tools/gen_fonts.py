#!/usr/bin/env python3
"""Generate EasyDeck's LVGL fonts.

Text: Barlow Semi Condensed (OFL) and Ubuntu (UFL). Icons: Material Design Icons (Apache 2.0). Every text font gets an icon
font of the same size as its LVGL fallback, so a label can mix text + icons.

Usage:  python3 tools/gen_fonts.py      (needs `npm install` in tools/)
Output: firmware/src/ui/fonts/*.c, fonts.h, Icons.h
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, "fonts")
OUT = os.path.join(HERE, "..", "firmware", "src", "ui", "fonts")
CONV = os.path.join(HERE, "node_modules", ".bin", "lv_font_conv")

# Latin + Latin-1 + Latin Extended-A + punctuation, arrows, degree, euro
TEXT_RANGES = "0x20-0x7E,0xA0-0x17F,0x2013-0x2014,0x2018-0x201E,0x2022,0x2026,0x20AC"

from mdi_map import ICONS   # Material Design Icons (Apache 2.0) codepoints
ICON_RANGE = ",".join(hex(c) for c in sorted(set(ICONS.values())))
ICON_TTF = "mdi.ttf"

ICON_SIZES = [12, 14, 16, 20, 24, 32, 48]

# Common emoji (monochrome Noto Emoji, OFL) so messages from phone users render instead of
# showing blanks. Chained as: text font -> icon font -> emoji font.
EMOJI_TTF = "NotoEmoji.ttf"
EMOJI_RANGE = ",".join([
    "0x1F600-0x1F64F",                      # smileys & gestures
    "0x1F44B-0x1F44F", "0x1F440", "0x1F64F", "0x1F4AA", "0x1F91D", "0x1F914", "0x1F923", "0x1F970",
    "0x1F973", "0x1F97A", "0x1F92F", "0x1F929", "0x1F92A", "0x1F92D", "0x1F971",
    "0x2764", "0x1F494", "0x1F495", "0x1F49C", "0x1F499", "0x1F49A", "0x1F49B", "0x1F5A4",
    "0x1F525", "0x1F389", "0x1F38A", "0x2705", "0x274C", "0x2714", "0x2B50", "0x1F31F", "0x1F4AF",
    "0x1F4CD", "0x1F6A8", "0x26A0", "0x1F198", "0x1F6D1", "0x1F3E0", "0x1F697", "0x1F6B6", "0x1F3D5",
    "0x26FA", "0x26F0", "0x1F3D4", "0x1F30A", "0x2600", "0x2601", "0x26C5", "0x1F327", "0x26C8",
    "0x1F329", "0x2744", "0x1F319", "0x1F321", "0x1F4A7", "0x2615", "0x1F37A", "0x1F355", "0x1F354",
    "0x1F382", "0x1F381", "0x1F4F7", "0x1F4F1", "0x1F50B", "0x1F4E1", "0x1F4E2", "0x1F514", "0x1F4AC",
    "0x1F9ED", "0x1F5FA", "0x1F415", "0x1F408", "0x1F426", "0x1F41F", "0x1F3A3", "0x1F6E5", "0x1F3C4",
    "0x1F6B4", "0x1F3C3", "0x1F44D", "0x1F4A9", "0x1F480", "0x1F47B", "0x1F916", "0x1F937", "0x1F926",
    "0x1F4A4", "0x1F4A5", "0x1F4A8", "0x23F0", "0x231B", "0x1F550", "0x1F4C5", "0x1F511", "0x1F512",
])

# Two type families, each with the same role slots so the UI can switch styles:
#   tac = Tactical (Barlow Semi Condensed, OFL)   mod = Modern / MeshOS-like (Ubuntu, UFL)
# Condensed Barlow reads small, so its pixel sizes are bumped up a little.
FAMILIES = {
  "tac": { "regular": "BarlowSemiCondensed-Medium.ttf", "bold": "BarlowSemiCondensed-SemiBold.ttf",
           "heavy": "BarlowSemiCondensed-Bold.ttf",
           "sizes": { 12: 14, 14: 16, 16: 18, 20: 22, 24: 26, 32: 34 } },
  "mod": { "regular": "Ubuntu-Regular.ttf", "bold": "Ubuntu-Medium.ttf", "heavy": "Ubuntu-Bold.ttf",
           "sizes": { 12: 12, 14: 14, 16: 16, 20: 20, 24: 24, 32: 32 } },
}
# slot name -> (nominal size, weight)
SLOTS = [("f12", 12, "bold"), ("f14", 14, "regular"), ("f14b", 14, "bold"), ("f16", 16, "regular"),
         ("f16b", 16, "bold"), ("f20", 20, "regular"), ("f20b", 20, "bold"), ("f24", 24, "regular"),
         ("f24b", 24, "bold"), ("f32b", 32, "heavy")]
TEXT_FONTS = []
for fam, cfg in FAMILIES.items():
    for slot, nominal, weight in SLOTS:
        TEXT_FONTS.append((f"{fam}_{slot}", cfg[weight], cfg["sizes"][nominal]))


def run(args):
    r = subprocess.run(args, capture_output=True, text=True, cwd=HERE)
    if r.returncode != 0:
        print(r.stdout, r.stderr)
        sys.exit(1)


def conv(name, size, sources, fallback=None):
    # relative paths so no local directory names end up in the generated files
    args = [CONV, "--bpp", "4", "--size", str(size), "--format", "lvgl", "--no-compress",
            "--lv-include", "lvgl.h", "-o", os.path.relpath(os.path.join(OUT, name + ".c"), HERE),
            "--lv-font-name", name]
    if fallback:
        args += ["--lv-fallback", fallback]
    for ttf, rng in sources:
        args += ["--font", os.path.join("fonts", ttf), "-r", rng]
    run(args)
    print("  ", name)


def nearest_icon(size):
    return min(ICON_SIZES, key=lambda s: abs(s - size))


def main():
    os.makedirs(OUT, exist_ok=True)
    for s in ICON_SIZES:
        conv(f"emoji_{s}", s, [(EMOJI_TTF, EMOJI_RANGE)])
        conv(f"icons_{s}", s, [(ICON_TTF, ICON_RANGE)], fallback=f"emoji_{s}")
    for name, ttf, size in TEXT_FONTS:
        conv(name, size, [(ttf, TEXT_RANGES)], fallback=f"icons_{nearest_icon(size)}")

    with open(os.path.join(OUT, "fonts.h"), "w") as f:
        f.write("#pragma once\n// generated by tools/gen_fonts.py — do not edit\n#include <lvgl.h>\n\n")
        for s in ICON_SIZES:
            f.write(f"LV_FONT_DECLARE(emoji_{s});\n")
            f.write(f"LV_FONT_DECLARE(icons_{s});\n")
        for name, _, _ in TEXT_FONTS:
            f.write(f"LV_FONT_DECLARE({name});\n")

    with open(os.path.join(OUT, "Icons.h"), "w") as f:
        f.write("#pragma once\n// generated by tools/gen_fonts.py — Material Design Icons glyphs as UTF-8 strings\n\n")
        for k, cp in sorted(ICONS.items()):
            utf8 = chr(cp).encode("utf-8")
            esc = "".join(f"\\x{b:02X}" for b in utf8)
            f.write(f'#define IC_{k:<14} "{esc}"\n')


if __name__ == "__main__":
    main()
